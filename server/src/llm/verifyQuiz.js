import { generateText } from "./client.js";
import { QuizAuditReportSchema } from "./schemas/verifierSchema.js";
import {
  VERIFIER_SYSTEM_INSTRUCTION,
  buildVerifierPrompt,
} from "./prompts/verifierPrompt.v1.js";

function cleanJsonString(raw) {
  if (!raw) return "";
  let cleaned = raw.trim();
  if (cleaned.startsWith("```json")) {
    cleaned = cleaned.replace(/^```json\s*/, "").replace(/\s*```$/, "");
  } else if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```\s*/, "").replace(/\s*```$/, "");
  }
  return cleaned.trim();
}

/**
 * Executes a blind quality verification pass on questions.
 * Compares Generator's declared correctIndex against Verifier's independently solvedIndex.
 *
 * @param {Array<Object>} questions - The questions generated by Phase 1/5
 * @returns {Promise<Object>} Verification audit report with consensus scores
 */
export async function verifyQuiz(questions) {
  if (!Array.isArray(questions) || questions.length === 0) {
    throw new Error("No questions provided to verify.");
  }

  const prompt = buildVerifierPrompt(questions);

  const { text: rawOutput, metrics } = await generateText({
    prompt,
    systemInstruction: VERIFIER_SYSTEM_INSTRUCTION,
    responseMimeType: "application/json",
  });

  const cleaned = cleanJsonString(rawOutput);
  let parsed;
  try {
    parsed = JSON.parse(cleaned);
  } catch (err) {
    throw new Error(`Verifier output failed JSON parsing: ${err.message}`);
  }

  const validation = QuizAuditReportSchema.safeParse(parsed);
  if (!validation.success) {
    throw new Error("Verifier output failed Zod audit schema validation");
  }

  const auditReport = validation.data;

  // Cross-reference generator's intended answer with verifier's blind answer:
  const enrichedAudits = auditReport.audits.map((audit) => {
    const originalQ = questions[audit.questionIndex];
    const generatorIndex = originalQ?.correctIndex;
    const consensusMatch = generatorIndex === audit.solvedIndex;

    return {
      ...audit,
      generatorIndex,
      consensusMatch,
      status: consensusMatch && !audit.isAmbiguous ? "VERIFIED" : "FLAGGED",
    };
  });

  const matchingCount = enrichedAudits.filter((a) => a.consensusMatch).length;
  const consensusRate = Math.round((matchingCount / questions.length) * 100);

  return {
    verified: consensusRate >= 80,
    consensusRate,
    overallConfidence: auditReport.overallConfidence,
    summary: auditReport.summary,
    audits: enrichedAudits,
    metrics,
  };
}
