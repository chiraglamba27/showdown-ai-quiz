import { z } from "zod";

/**
 * Schema for an individual question.
 * Enforces strict constraints on options, indexing, and prohibited phrases.
 */
export const QuestionSchema = z
  .object({
    question: z
      .string()
      .trim()
      .min(10, "Question must be at least 10 characters long"),

    options: z
      .array(z.string().trim().min(1, "Option cannot be empty"))
      .length(4, "Must contain exactly 4 options"),

    correctIndex: z
      .number()
      .int()
      .min(0, "correctIndex must be between 0 and 3")
      .max(3, "correctIndex must be between 0 and 3"),

    explanation: z
      .string()
      .trim()
      .min(10, "Explanation must be at least 10 characters long"),

    difficulty: z.enum(["easy", "medium", "hard"], {
      errorMap: () => ({ message: "Difficulty must be 'easy', 'medium', or 'hard'" }),
    }),
  })
  .refine(
    (data) => {
      // Ensure all 4 options are unique (case-insensitive)
      const normalized = data.options.map((opt) => opt.trim().toLowerCase());
      const uniqueCount = new Set(normalized).size;
      return uniqueCount === 4;
    },
    {
      message: "All 4 options must be distinct. Duplicate options are prohibited.",
      path: ["options"],
    }
  )
  .refine(
    (data) => {
      // Prohibit phrases like "all of the above" or "none of the above"
      // because options are randomized in multiplayer sessions
      const forbidden = /all of the above|none of the above|both [a-d] and [a-d]/i;
      return !data.options.some((opt) => forbidden.test(opt));
    },
    {
      message: "Options must not contain 'all of the above', 'none of the above', or cross-option references.",
      path: ["options"],
    }
  );

/**
 * Schema for the full quiz generated by the model.
 */
export const QuizSchema = z.object({
  topic: z.string().trim().min(2, "Topic must be at least 2 characters"),
  questions: z
    .array(QuestionSchema)
    .min(1, "Quiz must contain at least 1 question"),
});
